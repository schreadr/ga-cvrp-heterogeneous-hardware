#ifndef PROCESSING_NODE_HPP
#define PROCESSING_NODE_HPP

#include "hls_stream.h"
#include "ap_axi_sdata.h"

// User-configurable encoding constants 
#define COORD_BITS       7
#define CAPACITY_BITS    6

// User-configurable problem max size constants
#define MAX_BEATS_PER_INDIVIDUAL 64

// Encoding constants
#define AXI_WIDTH        512
#define AXI_BYTES        (AXI_WIDTH / 8)
#define DEPOT_BITS       1
#define FIELD_BITS       (2 * COORD_BITS + CAPACITY_BITS + DEPOT_BITS)
#define FIELDS_PER_BEAT  (AXI_WIDTH / FIELD_BITS)                             

// Struct providing full AXI4-Stream signal bundle expected by Coyote (data path)
typedef ap_axiu<AXI_WIDTH, 0, 0, 0> axi_word_t;

// Continuously reads pairs of individuals from in_stream, swaps them, and writes
// to out_stream. Free-running (infinite loop); processes one batch
// (num_individuals) per iteration.
//
// The configuration (num_individuals, beats_per_individual) is supplied directly
// as scalar arguments -- in hardware these are the live AXI4-Lite registers
// programmed by software via setCSR, so no separate config channel / spin-wait
// process is needed.
void swap_stream(
    hls::stream<axi_word_t> &in_stream,
    hls::stream<axi_word_t> &out_stream,
    int num_individuals,
    int beats_per_individual
);

// Top-level: two independent, free-running streams.
//
// The configuration values are scalar arguments of this function. Each of them
// is mapped to an AXI4-Lite register of the control interface generated by
// Vitis HLS (bundle 'control'), so the control register handling is done by HLS,
// no custom register parser is needed anymore.
//
// Register map of the generated AXI4-Lite 'control' interface (byte offsets):
//   0x10 : num_individuals0
//   0x18 : num_individuals1
//   0x20 : beats_per_individual
// (0x00-0x0F are reserved for the AXI4-Lite control block itself.)
//
// The software programs these registers with setCSR(...) before streaming data;
// software must write beats_per_individual last. The kernel is free-running
// (ap_ctrl_none): it runs from the moment the bitstream is loaded, spins while
// the configuration registers still hold zero and, once they are programmed,
// latches the configuration and continuously processes both data streams.
void processing_node(
    hls::stream<axi_word_t> &in0,
    hls::stream<axi_word_t> &out0,
    hls::stream<axi_word_t> &in1,
    hls::stream<axi_word_t> &out1,
    int num_individuals0,
    int num_individuals1,
    int beats_per_individual,
    // Hardware Debug Probe Ports
    int *dbg_num_individuals0,
    int *dbg_num_individuals1,
    int *dbg_beats_per_individual
);

#endif
